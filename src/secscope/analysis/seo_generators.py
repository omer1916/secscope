"""Generated launch files (SPEC §7.3): robots.txt, sitemap.xml, JSON-LD and title/description drafts.

Drafts are written next to the report (``patches/``); the user's source is never modified.
Title/description proposals are editable templates built from the page's own headings —
not AI-written copy.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from urllib.parse import urlsplit
from xml.sax.saxutils import escape

from secscope.analysis.seo import TITLE_MAX, Page


def _public_url(page: Page, production_origin: str | None) -> str:
    if not production_origin:
        return page.url
    p = urlsplit(page.url)
    return production_origin.rstrip("/") + (p.path or "/") + (f"?{p.query}" if p.query else "")


def robots_txt(production_origin: str | None, *, ai_crawlers: dict[str, bool] | None = None) -> str:
    """A permissive robots.txt with a Sitemap line. AI crawler rules only if the user chose them."""
    base = (production_origin or "https://www.example.com").rstrip("/")
    lines = ["User-agent: *", "Allow: /", ""]
    for agent, allowed in (ai_crawlers or {}).items():
        lines += [f"User-agent: {agent}", "Allow: /" if allowed else "Disallow: /", ""]
    lines.append(f"Sitemap: {base}/sitemap.xml")
    return "\n".join(lines) + "\n"


def sitemap_xml(pages: list[Page], production_origin: str | None) -> str:
    """Sitemap of indexable 200 HTML pages (canonical-consistent), deterministic order."""
    today = datetime.now(UTC).date().isoformat()
    seen: set[str] = set()
    rows: list[str] = []
    for p in sorted(pages, key=lambda x: x.path):
        if p.status != 200 or not p.is_html or p.noindex or p.robots_blocked:
            continue
        canon = (
            p.canonicals[0] if len(p.canonicals) == 1 and urlsplit(p.canonicals[0]).scheme else None
        )
        loc = canon or _public_url(p, production_origin)
        if loc in seen:
            continue
        seen.add(loc)
        rows.append(f"  <url><loc>{escape(loc)}</loc><lastmod>{today}</lastmod></url>")
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "\n".join(rows)
        + "\n</urlset>\n"
    )


def jsonld_templates(home: Page | None, production_origin: str | None) -> str:
    """Organization + WebSite JSON-LD prefilled from the home page — to be checked by a human."""
    base = (production_origin or "https://www.example.com").rstrip("/") + "/"
    name = (
        (home.og.get("og:site_name") or home.title or "Your site name")
        if home
        else "Your site name"
    )
    if " – " in name or " | " in name or " - " in name:
        name = name.replace(" | ", " – ").replace(" - ", " – ").split(" – ")[0]
    org = {
        "@context": "https://schema.org",
        "@type": "Organization",
        "name": name,
        "url": base,
        "logo": base + "logo.png",
    }
    site = {"@context": "https://schema.org", "@type": "WebSite", "name": name, "url": base}

    def block(d: dict[str, str]) -> str:
        body = json.dumps(d, indent=2, ensure_ascii=False)
        return '<script type="application/ld+json">\n' + body + "\n</script>"

    return (
        "<!-- Generated by SecScope: verify every value matches what the page shows. -->\n"
        + block(org)
        + "\n"
        + block(site)
        + "\n"
    )


def title_suggestions(pages: list[Page], site_name: str | None) -> list[dict[str, str]]:
    """For pages with a missing/too long/duplicate title: an editable proposal from the H1."""
    out: list[dict[str, str]] = []
    titles = [p.title for p in pages if p.title]
    for p in pages:
        if p.status != 200 or not p.is_html or p.noindex:
            continue
        problem = None
        if not p.title:
            problem = "missing"
        elif len(p.title) > TITLE_MAX:
            problem = "too long"
        elif titles.count(p.title) > 1:
            problem = "duplicate"
        if problem is None:
            continue
        h1 = (
            next((t for lvl, t in p.h if lvl == 1 and t), None)
            or p.path.strip("/").replace("-", " ").title()
            or "Home"
        )
        proposal = f"{h1} – {site_name}" if site_name and site_name not in h1 else h1
        out.append(
            {
                "url": p.url,
                "problem": problem,
                "current": p.title or "",
                "proposal": proposal[:TITLE_MAX],
            }
        )
    return out
